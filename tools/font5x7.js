const YUKSEKLIK = 7;
const GENISLIK = 5;

/* Bir metnin olcegi (kalan bosluk haric) ve piksel genisligi */
function olc(metin, olcek) {
  const karakter = metin.toUpperCase();
  const bosluk = GENISLIK + 1;
  return {
    karakter,
    genislik: karakter.length === 0 ? 0
      : karakter.length * GENISLIK * olcek + (karakter.length - 1) * olcek,
    yukseklik: YUKSEKLIK * olcek
  };
}

/* Metni ciz. bilgi = { gorsel, veri, genislik, yukseklik } (RGBA) */
function ciz(bilgi, metin, x, y, olcek, renk) {
  const o = olc(metin, olcek);
  let cx = x;
  for (let i = 0; i < o.karakter.length; i++) {
    const glif = G[o.karakter[i]];
    if (!glif) continue;                       // bilinmeyen karakter: atla
    for (let r = 0; r < YUKSEKLIK; r++) {
      for (let c = 0; c < GENISLIK; c++) {
        if (glif[r][c] !== '#') continue;
        for (let dy = 0; dy < olcek; dy++) {
          for (let dx = 0; dx < olcek; dx++) {
            nokta(bilgi, cx + c * olcek + dx, y + r * olcek + dy, renk);
          }
        }
      }
    }
    cx += (GENISLIK + 1) * olcek;
  }
  return o.genislik;
}

function nokta(bilgi, x, y, renk) {
  if (x < 0 || y < 0 || x >= bilgi.genislik || y >= bilgi.yukseklik) return;
  const i = (y * bilgi.genislik + x) * 4;
  const a = renk[3] === undefined ? 255 : renk[3];
  if (a === 255) {
    bilgi.veri[i] = renk[0]; bilgi.veri[i + 1] = renk[1];
    bilgi.veri[i + 2] = renk[2]; bilgi.veri[i + 3] = 255;
  } else {
    const k = a / 255, ik = 1 - k;
    bilgi.veri[i] = renk[0] * k + bilgi.veri[i] * ik;
    bilgi.veri[i + 1] = renk[1] * k + bilgi.veri[i + 1] * ik;
    bilgi.veri[i + 2] = renk[2] * k + bilgi.veri[i + 2] * ik;
    bilgi.veri[i + 3] = 255;
  }
}

